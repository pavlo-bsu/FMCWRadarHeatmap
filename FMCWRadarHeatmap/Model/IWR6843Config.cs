using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Numerics;
using System.Text;
using System.Threading.Tasks;
using Pavlo.MyHelpers.Physics;

namespace Pavlo.FMCWRadarHeatmap.Model
{
    /// <summary>
    /// class for configuration of Texas instruments (c) IWR6843 radar sensor. Model level
    /// Appropriate .cfg file of TI Out-of-Box demo (mmWave SDK 3.x) should be provided.
    /// Only legacy frame mode (dfeDataOutputMode 1) with a single profile is supported.
    /// </summary>
    public class IWR6843Config
    {
        private IReadOnlyList<string> _Commands = Array.Empty<string>();
        /// <summary>
        /// command lines of the .cfg file (without comments and blank lines) in the order to be sent to the CLI port
        /// </summary>
        public IReadOnlyList<string> Commands
        {
            get => _Commands;
            private set { _Commands = value; }
        }

        private double _FreqSlope = 0d;
        /// <summary>
        /// chirp slope (profileCfg freqSlopeConst).
        /// [MHz/us]
        /// </summary>
        public double FreqSlope
        {
            get => _FreqSlope;
            private set { _FreqSlope = value; }
        }

        private int _NumAdcSamples = 0;
        /// <summary>
        /// number of ADC samples per chirp (profileCfg numAdcSamples)
        /// </summary>
        public int NumAdcSamples
        {
            get => _NumAdcSamples;
            private set { _NumAdcSamples = value; }
        }

        private double _SampleRate = 0d;
        /// <summary>
        /// ADC sampling rate (profileCfg digOutSampleRate).
        /// [ksps]
        /// </summary>
        public double SampleRate
        {
            get => _SampleRate;
            private set { _SampleRate = value; }
        }

        private double _FramePeriodicity = 0d;
        /// <summary>
        /// frame period (frameCfg framePeriodicity).
        /// [ms]
        /// </summary>
        public double FramePeriodicity
        {
            get => _FramePeriodicity;
            private set { _FramePeriodicity = value; }
        }

        private bool _IsRangeAzimuthHeatmapEnabled = false;
        /// <summary>
        /// is the range-azimuth heatmap (TLV 4) sent by the sensor (guiMonitor rangeAzimuthHeatMap)
        /// </summary>
        public bool IsRangeAzimuthHeatmapEnabled
        {
            get => _IsRangeAzimuthHeatmapEnabled;
            private set { _IsRangeAzimuthHeatmapEnabled = value; }
        }

        /// <summary>
        /// number of range bins, i.e. size of the range FFT (NumAdcSamples rounded up to a power of 2)
        /// </summary>
        public int NumRangeBins
        {
            get => (int)BitOperations.RoundUpToPowerOf2((uint)NumAdcSamples);
        }

        /// <summary>
        /// distance between neighboring range bins.
        /// [m]
        /// </summary>
        public double RangeBinSize
        {
            get => Constants.c * (SampleRate * 1e3) / (2 * (FreqSlope * 1e12) * NumRangeBins);
        }

        private IWR6843Config()
        { }

        /// <summary>
        /// read and parse the .cfg file
        /// </summary>
        public static IWR6843Config Load(string filePath)
        {
            return Parse(File.ReadLines(filePath));
        }

        /// <summary>
        /// parse lines of a .cfg file which is generated by TI Out-of-Box demo (mmWave SDK 3.x)
        /// </summary>
        /// <exception cref="FormatException">a command is missing or has wrong arguments</exception>
        /// <exception cref="NotSupportedException">the frame mode is not legacy, or there are several profiles</exception>
        public static IWR6843Config Parse(IEnumerable<string> lines)
        {
            var config = new IWR6843Config();
            var commands = new List<string>();
            bool isProfileFound = false, isFrameFound = false, isGuiMonitorFound = false;

            foreach (string rawLine in lines)
            {
                string line = rawLine.Trim();
                //'%' starts a comment
                if (line.Length == 0 || line.StartsWith('%'))
                    continue;
                commands.Add(line);

                string[] words = line.Split(' ', StringSplitOptions.RemoveEmptyEntries);
                //arguments after the command word
                string[] args = words[1..];
                switch (words[0])
                {
                    case "dfeDataOutputMode":
                        if (GetInt(args, 0, line) != 1)
                            throw new NotSupportedException($"Only legacy frame mode is supported: \"{line}\"");
                        break;
                    case "profileCfg":
                        if (isProfileFound)
                            throw new NotSupportedException($"Only a single profile is supported: \"{line}\"");
                        config.FreqSlope = GetDouble(args, 7, line);
                        config.NumAdcSamples = GetInt(args, 9, line);
                        config.SampleRate = GetDouble(args, 10, line);
                        isProfileFound = true;
                        break;
                    case "frameCfg":
                        config.FramePeriodicity = GetDouble(args, 4, line);
                        isFrameFound = true;
                        break;
                    case "guiMonitor":
                        config.IsRangeAzimuthHeatmapEnabled = GetInt(args, 4, line) == 1;
                        isGuiMonitorFound = true;
                        break;
                }
            }

            if (!isProfileFound)
                throw new FormatException("\"profileCfg\" command is missing.");
            if (!isFrameFound)
                throw new FormatException("\"frameCfg\" command is missing.");
            if (!isGuiMonitorFound)
                throw new FormatException("\"guiMonitor\" command is missing.");
            if (config.FreqSlope <= 0 || config.NumAdcSamples <= 0 || config.SampleRate <= 0)
                throw new FormatException("\"profileCfg\" must have positive slope, number of ADC samples and sampling rate.");

            config.Commands = commands;
            return config;
        }

        private static string GetArg(string[] args, int index, string line)
        {
            if (index >= args.Length)
                throw new FormatException($"Too few arguments: \"{line}\"");
            return args[index];
        }

        private static int GetInt(string[] args, int index, string line)
        {
            if (!int.TryParse(GetArg(args, index, line), NumberStyles.Integer, CultureInfo.InvariantCulture, out int value))
                throw new FormatException($"Argument {index + 1} is not an integer: \"{line}\"");
            return value;
        }
        
        //the .cfg file uses '.' as decimal separator regardless of the PC culture
        private static double GetDouble(string[] args, int index, string line)
        {
            if (!double.TryParse(GetArg(args, index, line), NumberStyles.Float, CultureInfo.InvariantCulture, out double value))
                throw new FormatException($"Argument {index + 1} is not a number: \"{line}\"");
            return value;
        }
    }
}
